#!/usr/bin/env bash
set -euo pipefail

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
project_dir="$(cd -- "$script_dir/.." && pwd)"
mkdir -p "$project_dir/docs/linux" "$project_dir/notes" "$project_dir/scripts"

for tool in git curl systemctl ip ss free df; do
  if ! command -v "$tool" >/dev/null 2>&1; then
    printf 'Required baseline tool missing: %s\n' "$tool" >&2
    exit 1
  fi
done

# Inspect only local environment metadata. Do not collect credentials or env vars.
report="$project_dir/docs/linux/ENVIRONMENT.txt"
if [ -e "$report" ] && ! grep -q '^Generated by verify-foundation.sh$' "$report"; then
  printf 'Preserving existing environment report: %s\n' "$report" >&2
  exit 1
fi
{
  printf 'Generated by verify-foundation.sh\n\n'
  printf 'PROJECT\n%s\n\n' "$project_dir"
  printf 'OS\n'
  cat /etc/os-release
  printf '\nUSER\n'
  id
  printf '\nINIT\n'
  ps -p 1 -o comm=
  printf '\nSYSTEMD\n'
  systemctl is-system-running
  printf '\nPROCESSORS\n'
  nproc
  printf '\nMEMORY\n'
  free -h
  printf '\nPROJECT AND LINUX FILESYSTEMS\n'
  df -h "$project_dir" /
  printf '\nGIT\n'
  git --version
  printf '\nCURL\n'
  curl --version | head -n 1
} > "$report"

if [ ! -e "$project_dir/.gitignore" ]; then
  cat > "$project_dir/.gitignore" <<'EOF'
.env
.env.*
!.env.example
node_modules/
dist/
*.key
*.pem
*.pfx
kubeconfig*
.kube/
EOF
fi
printf 'Workspace ready: %s\n' "$project_dir"
printf 'Verification report: %s\n' "$report"
printf 'Baseline tools: OK\n'
